export const EXERCISES = [...BASE_EXERCISES, ...EXTRA_EXERCISES];
/**
 * 「动作选择」页的部位分区。和引擎排表用的 AREA_PATTERN 不是同一套：
 * 排表要的是「这天能不能顶主项」，这里要的是「用户想找肩的动作时能翻到哪些」，
 * 所以按主动肌（muscles[0]）归类，一个动作只落在它主要练的那个区里。
 */
export const BROWSE_AREAS = [
    { key: 'chest', title: '胸部训练', test: (ex) => /胸/.test(ex.muscles[0] ?? '') },
    { key: 'back', title: '背部训练', test: (ex) => /背|菱形|后链|斜方/.test(ex.muscles[0] ?? '') },
    { key: 'shoulder', title: '肩部训练', test: (ex) => /三角|肩袖|肩/.test(ex.muscles[0] ?? '') },
    { key: 'arm', title: '手臂训练', test: (ex) => /二头|三头|肱桡/.test(ex.muscles[0] ?? '') },
    { key: 'leg', title: '腿部训练', test: (ex) => /股四|腘绳|小腿/.test(ex.muscles[0] ?? '') },
    { key: 'glute', title: '臀部训练', test: (ex) => /臀|腘绳/.test(ex.muscles[0] ?? '') },
    { key: 'core', title: '核心训练', test: (ex) => /核心|腹/.test(ex.muscles[0] ?? '') },
    { key: 'cardio', title: '有氧与体能', test: (ex) => ex.pattern === 'cardio' }
];
/** 一个动作在分区里出现的那几类（提踵这种一处就够，臀腿两类的动作会同时出现） */
export function browseAreasOf(ex) {
    return BROWSE_AREAS.filter((a) => a.test(ex)).map((a) => a.key);
}
export const BY_ID = new Map(EXERCISES.map((e) => [e.id, e]));
export function byId(id) {
    return id ? BY_ID.get(id) : undefined;
}
/** 用户说了「在家练、只有哑铃」时，只用得上这几样 */
export const HOME_EQ = ['哑铃', '自重', '引体杆'];
export function fitsEquipment(ex, homeOnly) {
    if (!homeOnly)
        return true;
    return ex.equipment.some((e) => HOME_EQ.includes(e));
}
/** 同类动作里挑一个家里做得出来的；挑不出来就返回 null，由调用方把这一项去掉并说明 */
export function homeSwap(ex, areas) {
    return swapCandidates(ex, areas).find((c) => fitsEquipment(c, true)) ?? null;
}
/**
 * 换动作：同动作模式、避开伤病部位，优先器械熟悉度高、肌群重合多的。
 * 器械有交集只作为排序偏好，不作为硬过滤，否则有伤时常常一个候选都剩不下。
 */
export function swapCandidates(ex, areas) {
    const pool = EXERCISES.filter((c) => c.id !== ex.id && c.pattern === ex.pattern && !isBlocked(c, areas));
    const sharedMuscles = (x) => x.muscles.filter((m) => ex.muscles.includes(m)).length;
    const eqOverlap = (x) => x.equipment.filter((eq) => ex.equipment.includes(eq)).length;
    return pool.sort((a, b) => {
        return (cautionHits(a, areas) - cautionHits(b, areas) ||
            eqOverlap(b) - eqOverlap(a) ||
            sharedMuscles(b) - sharedMuscles(a) ||
            Number(b.heavy) - Number(a.heavy));
    });
}
/** 该部位有伤时是否必须换掉 */
export function isBlocked(ex, areas) {
    return areas.some((a) => Boolean(ex.avoid?.includes(a)));
}
/** 还能做但需要改的地方有几处 */
export function cautionHits(ex, areas) {
    return areas.filter((a) => Boolean(ex.caution?.[a])).length;
}
export function cautionText(ex, areas) {
    return areas.map((a) => ex.caution?.[a]).filter(Boolean).join('；');
}
