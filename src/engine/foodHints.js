/** 长词先走：命中「全麦面包」后就不再让「面包」重复计数 */
const BY_KEY_LENGTH = FOOD_HINTS
    .flatMap((hint) => hint.keys.map((key) => ({ key, hint })))
    .sort((a, b) => b.key.length - a.key.length);
function normalize(name) {
    return name.toLowerCase().replace(/[\s　]+/g, '');
}
/** 查表：输入为空给全表，否则按名字或别名对上的都算命中 */
export function searchFoods(q) {
    const s = normalize(q);
    if (!s)
        return FOOD_HINTS;
    return FOOD_HINTS.filter((h) => normalize(h.label).includes(s) || h.keys.some((k) => k.includes(s) || s.includes(k)));
}
/**
 * 按名字里出现的词对表。命不上就返回 null——宁可不给数，也不按「吃了饭」编一个。
 * 一条只算一份：吃了两份得自己乘，这个乘法留给人做。
 */
export function estimateMeal(name) {
    const s = normalize(name);
    if (!s)
        return null;
    const used = [];
    const items = [];
    for (const { key, hint } of BY_KEY_LENGTH) {
        if (items.includes(hint))
            continue;
        const idx = s.indexOf(key);
        if (idx < 0)
            continue;
        const end = idx + key.length;
        if (used.some(([a, b]) => idx < b && end > a))
            continue;
        used.push([idx, end]);
        items.push(hint);
    }
    if (!items.length)
        return null;
    return {
        items,
        low: items.reduce((x, h) => x + h.low, 0),
        high: items.reduce((x, h) => x + h.high, 0),
        nutrients: NUTRIENTS.flatMap((meta) => {
            const withNut = items.filter((h) => h.nut[meta.key]);
            if (!withNut.length)
                return [];
            return [
                {
                    key: meta.key,
                    label: meta.label,
                    unit: meta.unit,
                    low: round1(withNut.reduce((x, h) => x + (h.nut[meta.key]?.[0] ?? 0), 0)),
                    high: round1(withNut.reduce((x, h) => x + (h.nut[meta.key]?.[1] ?? 0), 0)),
                    items: withNut.length
                }
            ];
        })
    };
}
function round1(v) {
    return Math.round(v * 10) / 10;
}
